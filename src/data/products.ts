/** Builds the cartesian product of option values into concrete variants. */
function buildVariants(
  skuPrefix: string,
  axes: { name: VariantOptionName; values: string[] }[],
  /** Price delta per option value, keyed by value. Missing = 0. */
  deltas: Record<string, number>,
  basePrice: number,
  baseOldPrice: number | undefined,
  stockFor: (index: number) => number,
): Variant[] {
  const combos: Partial<Record<VariantOptionName, string>>[] = [{}];
  for (const axis of axes) {
    const next: Partial<Record<VariantOptionName, string>>[] = [];
    for (const combo of combos) {
      for (const value of axis.values) {
        next.push({ ...combo, [axis.name]: value });
      }
    }
    combos.length = 0;
    combos.push(...next);
  }

  return combos.map((options, i) => {
    const delta = Object.values(options).reduce(
      (sum, value) => sum + (deltas[value as string] ?? 0),
      0,
    );
    return {
      id: `${skuPrefix}-v${i + 1}`,
      sku: `${skuPrefix}-${Object.values(options).join("-").replace(/\s+/g, "").toUpperCase()}`,
      options,
      price: basePrice + delta,
      oldPrice: baseOldPrice ? baseOldPrice + delta : undefined,
      stock: stockFor(i),
      imageIndex: axes[0]?.name === "Color" ? i % 3 : 0,
    };
  });
}

